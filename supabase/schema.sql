CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  organization TEXT NOT NULL DEFAULT '',
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS pickups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  location TEXT NOT NULL,
  category TEXT NOT NULL,
  estimated_quantity_kg DOUBLE PRECISION NOT NULL,
  actual_quantity_kg DOUBLE PRECISION,
  pickup_at TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'Household',
  collector TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Pending',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS waste_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  pickup_id BIGINT UNIQUE REFERENCES pickups(id) ON DELETE SET NULL,
  category TEXT NOT NULL,
  quantity_kg DOUBLE PRECISION NOT NULL,
  source TEXT NOT NULL,
  sorting_method TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  logged_at TEXT NOT NULL,
  recovered_kg DOUBLE PRECISION NOT NULL DEFAULT 0,
  compost_kg DOUBLE PRECISION NOT NULL DEFAULT 0,
  resource_value_inr DOUBLE PRECISION NOT NULL DEFAULT 0,
  scrap_dealer_income_inr DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS impact_factors (
  id BIGINT PRIMARY KEY,
  co2_per_recovered_kg DOUBLE PRECISION NOT NULL DEFAULT 1.5,
  co2_per_compost_kg DOUBLE PRECISION NOT NULL DEFAULT 0.3,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_impact_factors (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  co2_per_recovered_kg DOUBLE PRECISION NOT NULL DEFAULT 1.5,
  co2_per_compost_kg DOUBLE PRECISION NOT NULL DEFAULT 0.3,
  updated_at TEXT NOT NULL
);

INSERT INTO impact_factors (id, co2_per_recovered_kg, co2_per_compost_kg, updated_at)
VALUES (1, 1.5, 0.3, NOW()::TEXT)
ON CONFLICT (id) DO NOTHING;

CREATE INDEX IF NOT EXISTS idx_logs_user_date ON waste_logs(user_id, logged_at);
CREATE INDEX IF NOT EXISTS idx_pickups_user_at ON pickups(user_id, pickup_at);
CREATE INDEX IF NOT EXISTS idx_pickups_user_status ON pickups(user_id, status);
CREATE INDEX IF NOT EXISTS idx_sessions_user_expiry ON sessions(user_id, expires_at);
